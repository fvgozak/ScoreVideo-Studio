import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const ctx={window:{}};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync('static/score-core.js','utf8'),ctx);
const F=ctx.window.ScoreFollower;
const f=new F({tempoMap:[{beat:0,second:0,tempo_us:500000}]});
assert.equal(f.drawRevision,0);
const fake=()=>({style:{clipPath:'',webkitClipPath:''}});
const item1={el:fake(),left:60,right:100,revealed:false,drawProgress:0,originalClipPath:'',originalWebkitClipPath:''};
const item2={el:fake(),left:160,right:200,revealed:false,drawProgress:0,originalClipPath:'',originalWebkitClipPath:''};
f.effects.drawScore=true;
f.drawItems=[item1,item2];
f.drawSystems=[{key:0,y:0,last:100,items:[item1,item2],lines:[],minLeft:60,maxRight:200,revealRight:59}];
f.container={offsetLeft:0,offsetTop:0};
f.positions=[{x:0,y:0,audio:0},{x:150,y:0,audio:1},{x:250,y:0,audio:2}];
f.drawingActive=true;
let version=f.drawRevision;
f.updateDrawing(1);
assert.equal(item1.revealed,true);assert.equal(item2.revealed,false);assert.equal(item2.drawProgress,0);assert.ok(f.drawSystems[0].revealRight>149&&f.drawSystems[0].revealRight<151.5);
assert.equal(f.drawRevision,version+1);
version=f.drawRevision;
f.updateDrawing(1);
assert.equal(f.drawRevision,version,'same engraved state should keep the same cache revision');
f.updateDrawing(2);
assert.equal(item2.revealed,true);assert.equal(f.drawRevision,version+1);
f.updateDrawing(0);
assert.equal(item1.revealed,false);assert.equal(item2.revealed,false);
assert.equal(f.drawRevision,version+2,'seeking backward must invalidate reveal cache');
console.log('Drawing revision is stable between unchanged frames, advances at note reveal and seek');
