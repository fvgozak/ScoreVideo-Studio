const assert=require('node:assert/strict');
const fs=require('fs'),vm=require('node:vm');
const c={window:{},document:{}};
vm.createContext(c);
for(const f of ['studio-scene.js','score-core.js','stage-runtime.js'])vm.runInContext(fs.readFileSync('static/'+f,'utf8'),c,{filename:f});
const S=c.window.ScoreStudio;
const absolute=S.normalize({lightColorMode:'aurora',velocityScale:'absolute',auroraLow:'#0000ff',auroraHigh:'#ff0000'});
const relative=S.normalize({...absolute,velocityScale:'relative'});
const range={min:45,max:85};
assert.equal(S.noteLightColor(relative,45,'#ffffff',range),'#0000ff');
assert.equal(S.noteLightColor(relative,85,'#ffffff',range),'#ff0000');
assert.notEqual(S.noteLightColor(absolute,45,'#ffffff',range),'#0000ff');
assert.equal(S.normalizedVelocity(50,'relative',{min:50,max:50}),64);
assert.equal(S.noteLightColor(relative,50,'#ffffff',{min:50,max:50}),S.noteLightColor(absolute,64,'#ffffff'));
assert.equal(c.window.ScoreStage.normalized({scene:{velocityScale:'relative'}}).scene.velocityScale,'relative');
const src=fs.readFileSync('static/index.html','utf8');
assert.ok(src.includes('fullscreenPreviewButton'));
assert.ok(src.includes('velocityScale'));
assert.ok(src.includes('data-editor-tab="project"'));
const code=fs.readFileSync('static/app.js','utf8');
assert.ok(code.includes('requestFullscreen'));
assert.ok(code.includes('fullscreenchange'));
assert.ok(code.includes("meta.score_name.replace"));
console.log('v0.16 palette range + fullscreen integration + file-name title configuration passed');
